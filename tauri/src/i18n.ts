  `${errorMessages[code.toUpperCase()]?.[language === "en" ? 0 : 1] || translator(language)("generic")} (${code})`;
export const errorText = localizedError;
export function phaseText(language: Language, phase: string) {
  const phases: Record<string, Key> = {
    preparing: "preparing",
    splitting: "split",
    word: "word",
    merging: "merge",
    unlocking: "unlock",
    markdown: "markdown",
    committing: "committing",
  };
  return translator(language)(phases[phase] || "pending");
}
